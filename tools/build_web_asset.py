#!/usr/bin/env python3
"""Inline fit.js + app.js into tuning.html, gzip, and emit src/web/tuning_html_gz.c
— the gzipped tuning SPA as a C byte array, compiled into the firmware and served
at GET / with Content-Encoding: gzip.

Why a generated C array instead of CMake EMBED_FILES / board_build.embed_files:
under PlatformIO's ESP-IDF integration both toolchain embed paths are fragile —
EMBED_FILES double-registers the generated .S in PlatformIO's SCons build, and
board_build.embed_files emits the .S but never links it. A plain generated
source sidesteps all of that and is picked up by the same src/*.c glob as every
other source.

The dev page references the JS via <script type=module src="…">; here we strip
the import/export keywords and inline both modules into one classic-script scope
so the embedded page is fully self-contained (the device serves one file).

Deterministic gzip (mtime=0); the .c is only rewritten when its bytes change, so
running this as a pre-build step doesn't trigger spurious recompiles."""
import gzip, io, pathlib, re

web = pathlib.Path(__file__).resolve().parent.parent / "src" / "web"
html  = (web / "tuning.html").read_text()
fit   = (web / "fit.js").read_text()
align = (web / "align.js").read_text()
htmlesc = (web / "html.js").read_text()
app   = (web / "app.js").read_text()
# Third-party, inlined VERBATIM — no export/import rewriting may touch these.
uplot_js  = (web / "uplot.iife.min.js").read_text()
uplot_css = (web / "uplot.min.css").read_text()

# app.js imports from './fit.js', './align.js' and './html.js'; strip those
# imports once all three are inlined ahead of it.
app = re.sub(r"^\s*import\s+\{[^}]*\}\s+from\s+'\./(?:fit|align|html)\.js';\s*$", "", app, flags=re.M)
# fit.js, align.js and html.js use `export`; strip the keyword for the inlined
# (non-module) scope. The IIFE uPlot build needs no such treatment — it defines
# a global — which is exactly why the IIFE build is the one vendored.
fit_inl   = re.sub(r"\bexport\s+", "", fit)
align_inl = re.sub(r"\bexport\s+", "", align)
html_inl  = re.sub(r"\bexport\s+", "", htmlesc)

# uPlot's stylesheet is a <link> on the dev page; inline it for the device.
html = html.replace('<link rel=stylesheet href="uplot.min.css">',
                    f"<style>{uplot_css}</style>")
# Order matters: uPlot's global, then html + align + fit, then app, which uses all four.
html = html.replace('<script src="uplot.iife.min.js"></script>',
                    f"<script>{uplot_js}</script>")
html = html.replace('<script type=module src="html.js"></script>',
                    f"<script>{html_inl}</script>")
html = html.replace('<script type=module src="align.js"></script>',
                    f"<script>{align_inl}</script>")
html = html.replace('<script type=module src="fit.js"></script>',
                    f"<script>{fit_inl}</script>")
html = html.replace('<script type=module src="app.js"></script>',
                    f"<script>{app}</script>")

# Every replace above is a silent no-op if its marker drifts, which would ship a
# page whose app.js references a function that was never inlined. Fail the build
# instead.
assert "type=module" not in html and "import {" not in html, \
    "tuning.html: a module <script> tag or import was not inlined"

(web / "tuning.html.built").write_text(html)   # debug artifact (gitignored)

buf = io.BytesIO()
with gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0) as f:
    f.write(html.encode())
gz = buf.getvalue()

rows = []
for i in range(0, len(gz), 16):
    rows.append("    " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
c_src = (
    "/* GENERATED by tools/build_web_asset.py — do not edit.\n"
    " * Gzipped tuning SPA, served at GET / with Content-Encoding: gzip. */\n"
    "#include <stddef.h>\n"
    "const unsigned char tuning_html_gz[] = {\n" + "\n".join(rows) + "\n};\n"
    "const size_t tuning_html_gz_len = sizeof(tuning_html_gz);\n"
)

out = web / "tuning_html_gz.c"
# Idempotent: only rewrite when content changed, so a pre-build invocation
# doesn't bump the mtime (and force a recompile) on an unchanged page.
if not out.exists() or out.read_text() != c_src:
    out.write_text(c_src)
print(f"tuning SPA: {len(html)} B uncompressed -> gzip {len(gz)} B -> {out.name}")
