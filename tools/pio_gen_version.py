"""PlatformIO pre-build hook: regenerate <build_dir>/version.h from git before
every build, so FIRMWARE_VERSION_STR (shown in /version, the web header, the
touchscreen About screen, and stamped into run archives) is never stale.

Why a pre-build hook instead of CMake configure_file:
  * configure_file only ran at CMake *configure* time, so an incremental
    `pio run` kept the previous hash unless you `touch CMakeLists.txt`.
  * It wrote into one env's binary dir, but platformio.ini's `-I` pointed all
    envs at .pio/build/esp32dev — so `esp32dev-ota` read a sibling env's
    (often stale) version.h, forcing a "build esp32dev first" dance.
This hook runs on EVERY build and writes into THIS env's own $BUILD_DIR (which
platformio.ini adds to the include path as `-I .pio/build/${PIOENV}`), so a bare
`pio run -e esp32dev-ota -t upload` always embeds the current commit. It only
rewrites version.h when the string changes, so an unchanged version costs no
recompile.
"""
Import("env")  # noqa: F821  (SCons injects `env` and `Import` into this scope)
import subprocess, os

project_dir = env["PROJECT_DIR"]           # noqa: F821
build_dir   = env.subst("$BUILD_DIR")      # noqa: F821  -> .pio/build/<env>

try:
    version = subprocess.check_output(
        ["git", "describe", "--tags", "--always", "--dirty"],
        cwd=project_dir, text=True, stderr=subprocess.DEVNULL).strip() or "unknown"
except Exception:
    version = "unknown"

content = ('/* GENERATED by tools/pio_gen_version.py — do not edit.\n'
           ' * Build date/time come from esp_app_get_description() at runtime. */\n'
           '#pragma once\n'
           f'#define FIRMWARE_VERSION_STR "{version}"\n')

os.makedirs(build_dir, exist_ok=True)
path = os.path.join(build_dir, "version.h")
old = None
if os.path.exists(path):
    with open(path) as f:
        old = f.read()
if old != content:
    with open(path, "w") as f:
        f.write(content)
    print(f"pio_gen_version: FIRMWARE_VERSION_STR -> {version}")

# Also publish the same string as PROJECT_VER, which is what lands in the
# image's esp_app_desc.version — the ONLY version a *different* running image
# can read out of a firmware slot. ESP-IDF picks PROJECT_VER up from a
# version.txt in the project root (project.cmake
# __project_get_revision_from_version_file). It registers the file as a
# CMAKE_CONFIGURE_DEPENDS too, but only once it has seen it exist — see the
# bootstrap note below, which is why the write is followed by an mtime bump.
#
# Without this, PROJECT_VER fell back to IDF's own `git describe`, which runs at
# CMake *configure* time only and therefore froze: a build made on 2026-09-05
# still carried version "3525637" and date "Sep 1 2026" from the last
# reconfigure. That stale descriptor is why POST /ota could not report what it
# had just written (v2_backlog #26) and why ota_upload.py's downgrade check was
# comparing a meaningless string.
#
# It is written to the PROJECT dir, not $BUILD_DIR: CMake only looks there. That
# makes it shared across envs, which is harmless — every env derives it from the
# same `git describe`.
vpath = os.path.join(project_dir, "version.txt")
vold = None
if os.path.exists(vpath):
    with open(vpath) as f:
        vold = f.read()
if vold != version + "\n":
    with open(vpath, "w") as f:
        f.write(version + "\n")
    # Force the reconfigure that reads it. CMAKE_CONFIGURE_DEPENDS on version.txt
    # is registered by project.cmake only *inside* `if(EXISTS version.txt)` — so
    # a build dir last configured when the file was absent (a fresh checkout, or
    # any tree from before this hook existed) has no dependency on it and would
    # keep stamping the frozen PROJECT_VER forever. Bumping the mtime of the file
    # CMake definitely does depend on breaks that circle. mtime is not content,
    # so this never dirties the working tree.
    # Cost: one CMake reconfigure whenever the git version changes, i.e. once per
    # commit, not per build. Only esp_app_desc.c recompiles afterwards.
    os.utime(os.path.join(project_dir, "CMakeLists.txt"), None)
    print(f"pio_gen_version: PROJECT_VER -> {version} (version.txt; forcing reconfigure)")
